function patchFile(lang, newObj) {
  const filePath = path.join(i18nDir, `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Check if closing brace for a11y has a comma
  // We want to insert the new keys before the last '};'
  const lastClose = content.lastIndexOf('};');
  if (lastClose === -1) {
    console.error(`Cannot find ending '};' in ${lang}.ts`);
    return;
  }

  // Convert newObj into indented TypeScript object syntax
  const tsSnippet = Object.entries(newObj)
    .map(([sectionKey, sectionVal]) => {
      const innerProps = Object.entries(sectionVal)
        .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
        .join('\n');
      return `  ${sectionKey}: {\n${innerProps}\n  },`;
    })
    .join('\n\n');

  // Insert before lastClose
  // Ensure previous property has a comma
  const prefix = content.slice(0, lastClose).trimEnd();
  const endsWithComma = prefix.endsWith(',') || prefix.endsWith('{');
  const separator = endsWithComma ? '\n\n' : ',\n\n';

  const updated = prefix + separator + tsSnippet + '\n};\n';
  fs.writeFileSync(filePath, updated, 'utf8');
  console.log(`✔ Successfully patched ${lang}.ts`);
}

for (const [lang, obj] of Object.entries(TRANSLATIONS)) {
  patchFile(lang, obj);
}
