const i18nDir = path.join(__dirname, '..', 'src', 'i18n');

for (const [lang, dict] of Object.entries(translations)) {
  const filePath = path.join(i18nDir, `${lang}.ts`);
  if (!fs.existsSync(filePath)) continue;

  let content = fs.readFileSync(filePath, 'utf8');

  // Check if keys already exist
  if (content.includes('curatedGastronomy:')) {
    console.log(`${lang}.ts already updated.`);
    continue;
  }

  // Find the menu section
  // It has format:
  // menu: {
  //   ...
  // },
  const menuMatch = content.match(/menu:\s*\{([\s\S]*?)\n\s*\},/);
  if (menuMatch) {
    const originalMenu = menuMatch[0];
    const originalBody = menuMatch[1];
    
    // Build replacement lines
    const extraLines = Object.entries(dict)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    
    const newMenu = `menu: {${originalBody}\n${extraLines}\n  },`;
    content = content.replace(originalMenu, newMenu);
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Updated ${lang}.ts with menu translations.`);
  } else {
    console.warn(`Could not find menu block in ${lang}.ts`);
  }
}
